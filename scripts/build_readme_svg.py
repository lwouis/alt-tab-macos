def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--downloads', help='Override the preserved download count')
    parser.add_argument('--stars', help='Override the preserved GitHub star count')
    args = parser.parse_args()
    counts = {'downloads': '9.4M', 'stars': '16K'}
    if OUTPUT.exists():
        counts.update(re.findall(r'<!--(downloads|stars)-->([^<]+)', OUTPUT.read_text()))
    OUTPUT.write_text(build_svg(args.downloads or counts['downloads'], args.stars or counts['stars']))
    print(f'Wrote {OUTPUT.relative_to(ASSETS.parent.parent)} ({OUTPUT.stat().st_size:,} bytes)')


if __name__ == '__main__':
    main()
