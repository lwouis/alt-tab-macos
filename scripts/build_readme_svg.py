#!/usr/bin/env python3
"""Build the self-contained, animated README image using only the standard library.

Run manually after changing the layout or the source artwork in docs/readme.
Release automation updates the downloads/stars markers in main.svg; rebuilding
preserves those values unless --downloads or --stars overrides them.
"""

import argparse
import base64
import re
from html import escape
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent / 'docs' / 'readme'
OUTPUT = ASSETS / 'main.svg'


