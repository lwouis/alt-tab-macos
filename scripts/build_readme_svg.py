    icon = base64.b64encode((ASSETS / 'app-icon.webp').read_bytes()).decode('ascii')
    scene = (ASSETS / 'window-demo.svg').read_text()
    # Inline the SVG rather than referencing another file: SVGs loaded as images
    # cannot load external resources. Native SVG animations still run in this mode.
    scene = scene.replace('<svg ', '<svg x="0" y="422" width="736" height="414.22" ', 1)
